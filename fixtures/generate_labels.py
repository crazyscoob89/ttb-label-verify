def _font_path(kind: str) -> str:
    for p in _FONT_CANDIDATES[kind]:
        if os.path.exists(p):
            return p
    raise SystemExit(f"No usable font found for '{kind}'. Install DejaVu or run on Windows.")


def font(kind: str, size: int) -> ImageFont.FreeTypeFont:
    return ImageFont.truetype(_font_path(kind), size)


# --------------------------------------------------------------------------
# Drawing helpers
# --------------------------------------------------------------------------


def wrap(text: str, f: ImageFont.FreeTypeFont, max_w: int) -> list[str]:
    words, lines, cur = text.split(), [], ""
    for wd in words:
        trial = f"{cur} {wd}".strip()
        if f.getlength(trial) <= max_w:
            cur = trial
        else:
            if cur:
                lines.append(cur)
            cur = wd
    if cur:
        lines.append(cur)
    return lines


def centered(d: ImageDraw.ImageDraw, y: int, text: str, f: ImageFont.FreeTypeFont,
             fill=INK, spacing: int = 8) -> int:
    d.text((W / 2, y), text, font=f, fill=fill, anchor="ma")
    return y + int(f.size * 1.18) + spacing


def block(d: ImageDraw.ImageDraw, y: int, text: str, f: ImageFont.FreeTypeFont,
          max_w: int, fill=INK, spacing: int = 4) -> int:
    for ln in wrap(text, f, max_w):
        d.text((W / 2, y), ln, font=f, fill=fill, anchor="ma")
        y += int(f.size * 1.30)
    return y + spacing


def rule(d: ImageDraw.ImageDraw, y: int, width: int = 420, thickness: int = 3) -> int:
    d.rectangle([(W - width) // 2, y, (W + width) // 2, y + thickness], fill=INK)
    return y + thickness + 26


