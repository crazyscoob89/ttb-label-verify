"""
generate_labels.py -- programmatic synthetic TTB label fixture generator.

Per docs/BENCHMARK_PLAN.md (Stage 2). These fixtures are drawn deterministically
with Pillow from an explicit specification, NOT generated by any AI model, so the
ground truth is exact by construction: every character on every image is written
here in code.

Each fixture emits:
  - fixtures/images/<ID>.png          the synthetic label image
  - fixtures/ground_truth/<ID>.json   paired application record + per-field truth

Ground-truth semantics (per PLAN.md's four-state model + comparison-first framing):
  "application"  -- the applicant-declared record this label is compared AGAINST
  "label_actual" -- what is genuinely printed on the image (exact, by construction)
  "expected"     -- per-field TRUTH verdict of label-vs-declared:
                    match | mismatch | not-applicable
                    (needs-review is never a *truth* value -- it is an acceptable
                     engine OUTCOME under the Uncertainty Invariant, scored as a
                     referral by the harness, never as a false match/mismatch.)

Brand names are fictional. No real trade dress is reproduced.
"""

