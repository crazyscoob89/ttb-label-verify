def label_actual(spec: dict) -> dict:
    """Exactly what is printed on the image, by construction."""
    brand = spec.get("brand")
    if spec.get("brand_split_lines"):
        brand_rendered = " ".join(spec["brand_split_lines"])
    else:
        brand_rendered = brand
    return {
        "brand_name": brand,
        "brand_as_rendered": brand_rendered,
        "class_type": spec.get("class_type"),
        "alcohol_content": spec.get("abv_text"),
        "net_contents": spec.get("net_contents_text"),
        "bottler_info": spec.get("bottler_text"),
        "country_of_origin": spec.get("origin_text"),
        "government_warning": {
            "heading": spec.get("warning_heading", WARNING_HEADING),
            "body": spec.get("warning_body", WARNING_BODY),
            "heading_is_all_caps": spec.get("warning_heading", WARNING_HEADING).isupper(),
            "heading_is_bold": True,
            "body_is_bold": bool(spec.get("warning_body_bold", False)),
            "body_is_statutory_exact": spec.get("warning_body", WARNING_BODY) == WARNING_BODY,
        },
        "fine_print": spec.get("fine_print"),
    }


def main() -> int:
    IMG_DIR.mkdir(parents=True, exist_ok=True)
    GT_DIR.mkdir(parents=True, exist_ok=True)

    by_id = {f["id"]: f for f in FIXTURES}
    rendered: dict[str, Image.Image] = {}
    manifest = []

    for fx in FIXTURES:
        fid = fx["id"]
        if fx.get("derived_from"):
            parent = by_id[fx["derived_from"]]
            spec = parent["spec"]
            base = rendered[parent["id"]]
            img = TRANSFORMS[fx["transform"]](base.copy())
            application = dict(parent["application"])
            expected = dict(parent["expected"])
            injection = parent.get("injection")
        else:
            spec = fx["spec"]
            img = render(spec)
            rendered[fid] = img
            application = fx["application"]
            expected = fx["expected"]
            injection = fx.get("injection")

        img_path = IMG_DIR / f"{fid}.png"
        img.save(img_path, "PNG", optimize=True)

        gt = {
            "fixture_id": fid,
            "category": fx["category"],
            "commodity": fx["commodity"],
            "description": fx["description"],
            "image": f"images/{fid}.png",
            "synthetic": True,
            "generated_by": "fixtures/generate_labels.py (programmatic Pillow rendering, no AI)",
            "degraded": fx["category"] == "degraded",
            "derived_from": fx.get("derived_from"),
            "transform": fx.get("transform"),
            "application": application,
            "label_actual": label_actual(spec),
            "expected": expected,
            "statutory_warning_reference": {
                "citation": "27 CFR 16.21",
                "heading": WARNING_HEADING,
                "body": WARNING_BODY,
            },
            "notes": (
                "expected[] holds the TRUTH verdict of label-vs-declared per field "
                "(match/mismatch/not-applicable). needs-review is never a truth value; "
                "it is an acceptable engine outcome scored as a referral per PLAN.md's "
                "Uncertainty Invariant."
            ),
        }
        if injection:
            gt["injection"] = injection

        (GT_DIR / f"{fid}.json").write_text(json.dumps(gt, indent=2) + "\n", encoding="utf-8")

        manifest.append({
            "fixture_id": fid,
            "category": fx["category"],
            "commodity": fx["commodity"],
            "image": f"images/{fid}.png",
            "ground_truth": f"ground_truth/{fid}.json",
        })
        print(f"  {fid:<26} {fx['category']:<13} {img_path.name}")

    (ROOT / "manifest.json").write_text(
        json.dumps(
            {
                "fixture_count": len(manifest),
                "fields": FIELDS,
                "statutory_warning": {"citation": "27 CFR 16.21",
                                      "heading": WARNING_HEADING,
                                      "body": WARNING_BODY},
                "fixtures": manifest,
            },
            indent=2,
        ) + "\n",
        encoding="utf-8",
    )
    print(f"\n{len(manifest)} fixtures written to {ROOT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
