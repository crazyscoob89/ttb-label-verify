# Label renderer
# --------------------------------------------------------------------------


def render(spec: dict) -> Image.Image:
    img = Image.new("RGB", (W, H), BG)
    d = ImageDraw.Draw(img)

    # Decorative border.
    d.rectangle([28, 28, W - 28, H - 28], outline=(120, 106, 82), width=5)
    d.rectangle([44, 44, W - 44, H - 44], outline=(178, 166, 142), width=2)

    y = 110

    # Brand -- either single line, or split across decorative lines.
    if spec.get("brand_split_lines"):
        f_brand = font("serifbold", 76)
        for i, part in enumerate(spec["brand_split_lines"]):
            y = centered(d, y, part, f_brand, spacing=2)
            if i < len(spec["brand_split_lines"]) - 1:
                d.text((W / 2, y), "\u2022  \u25c6  \u2022", font=font("serif", 30),
                       fill=(140, 120, 90), anchor="ma")
                y += 52
        y += 16
    else:
        y = centered(d, y, spec["brand"], font("serifbold", 78), spacing=18)

    y = rule(d, y)

    if spec.get("tagline"):
        y = centered(d, y, spec["tagline"], font("serif", 30), fill=(96, 88, 74), spacing=18)

    y = centered(d, y, spec["class_type"], font("bold", 50), spacing=30)

    if spec.get("origin_text"):
        y = centered(d, y, spec["origin_text"], font("bold", 34), spacing=26)

    y += 10
    if spec.get("abv_text"):
        y = centered(d, y, spec["abv_text"], font("regular", 40), spacing=14)
    if spec.get("net_contents_text"):
        y = centered(d, y, spec["net_contents_text"], font("regular", 40), spacing=14)

    y += 18
    if spec.get("bottler_text"):
        y = block(d, y, spec["bottler_text"], font("regular", 30), 760, spacing=16)

    # Government warning block, anchored toward the lower third.
    warn_y = max(y + 40, 1010)
    heading = spec.get("warning_heading", WARNING_HEADING)
    body = spec.get("warning_body", WARNING_BODY)
    body_bold = spec.get("warning_body_bold", False)

    f_head = font("bold", 27)
    f_body = font("bold" if body_bold else "regular", 27)

    max_w = 800
    # Heading and the first body line share a line, as on real labels.
    first = f"{heading} "
    head_w = f_head.getlength(first)
    body_lines = wrap(body, f_body, max_w)

    # Re-wrap so line 1 leaves room for the heading.
    rewrapped: list[str] = []
    words = body.split()
    cur, limit = "", max_w - head_w
    for wd in words:
        trial = f"{cur} {wd}".strip()
        if f_body.getlength(trial) <= limit:
            cur = trial
        else:
            rewrapped.append(cur)
            cur = wd
            limit = max_w
    if cur:
        rewrapped.append(cur)
    body_lines = rewrapped

    x0 = (W - max_w) // 2
    d.text((x0, warn_y), first, font=f_head, fill=INK, anchor="la")
    if body_lines:
        d.text((x0 + head_w, warn_y), body_lines[0], font=f_body, fill=INK, anchor="la")
    ly = warn_y + int(f_body.size * 1.32)
    for ln in body_lines[1:]:
        d.text((x0, ly), ln, font=f_body, fill=INK, anchor="la")
        ly += int(f_body.size * 1.32)

    # Adversarial fine print (prompt injection fixture).
    if spec.get("fine_print"):
        d.text((W / 2, H - 78), spec["fine_print"], font=font("regular", 17),
               fill=(112, 108, 100), anchor="ma")

    return img


# --------------------------------------------------------------------------
# Degradation transforms (programmatic, deterministic)
# --------------------------------------------------------------------------


def _solve(matrix: list[list[float]], rhs: list[float]) -> list[float]:
    """Gaussian elimination -- avoids a numpy dependency."""
    n = len(rhs)
    m = [row[:] + [rhs[i]] for i, row in enumerate(matrix)]
    for col in range(n):
        piv = max(range(col, n), key=lambda r: abs(m[r][col]))
        m[col], m[piv] = m[piv], m[col]
        pv = m[col][col]
        for r in range(col + 1, n):
            factor = m[r][col] / pv
            for c in range(col, n + 1):
                m[r][c] -= factor * m[col][c]
    out = [0.0] * n
    for r in range(n - 1, -1, -1):
        s = m[r][n] - sum(m[r][c] * out[c] for c in range(r + 1, n))
        out[r] = s / m[r][r]
    return out


def perspective_coeffs(src: list[tuple[float, float]],
                       dst: list[tuple[float, float]]) -> list[float]:
    a, b = [], []
    for (sx, sy), (dx, dy) in zip(src, dst):
        a.append([dx, dy, 1, 0, 0, 0, -sx * dx, -sx * dy])
        b.append(sx)
        a.append([0, 0, 0, dx, dy, 1, -sy * dx, -sy * dy])
        b.append(sy)
    return _solve(a, b)


def warp(img: Image.Image) -> Image.Image:
    """Steep-angle photograph simulation."""
    src = [(0, 0), (W, 0), (W, H), (0, H)]
    dst = [(88, 42), (W - 26, 6), (W - 96, H - 44), (34, H - 12)]
    c = perspective_coeffs(src, dst)
    out = img.transform((W, H), Image.PERSPECTIVE, c,
                        resample=Image.BICUBIC, fillcolor=(58, 56, 54))
    return out.filter(ImageFilter.GaussianBlur(0.7))


def blur(img: Image.Image) -> Image.Image:
    """Out-of-focus capture."""
    return img.filter(ImageFilter.GaussianBlur(2.6))


def glare(img: Image.Image) -> Image.Image:
    """Specular highlight / flash blowout across part of the label."""
    overlay = Image.new("L", (W, H), 0)
    od = ImageDraw.Draw(overlay)
    cx, cy = int(W * 0.60), int(H * 0.42)
    for i in range(46, 0, -1):
        rx, ry = int(i * 11), int(i * 15)
        od.ellipse([cx - rx, cy - ry, cx + rx, cy + ry], fill=int(255 * (1 - i / 46.0) ** 1.4))
    overlay = overlay.filter(ImageFilter.GaussianBlur(40))
    white = Image.new("RGB", (W, H), (255, 255, 255))
    out = Image.composite(white, img, overlay)
    return out.filter(ImageFilter.GaussianBlur(0.8))


